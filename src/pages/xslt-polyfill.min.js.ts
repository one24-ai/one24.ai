// Serves the XSLT polyfill next to the feed. Browsers are removing native XSLT
// (Chrome 158, Nov 2026), so /rss.xml loads this to keep its styled view working.
// Browsers that still have native XSLT transform the feed before it runs.
import polyfill from "xslt-polyfill/xslt-polyfill.min.js?raw";

export function GET() {
	return new Response(polyfill, { headers: { "Content-Type": "text/javascript; charset=utf-8" } });
}
